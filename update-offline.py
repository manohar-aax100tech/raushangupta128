#!/usr/bin/env python3
"""Regenerate data/offline-data.js from the single editable influencer.json."""
import json
from pathlib import Path
folder=Path(__file__).resolve().parent
raw=(folder/'data/influencer.json').read_text(encoding='utf-8')
json.loads(raw)
(folder/'data/offline-data.js').write_text('/* Generated from influencer.json. Do not edit this file. */\nwindow.RAUSHAN_PORTFOLIO_DATA = '+raw.strip()+';\n',encoding='utf-8')
print('Updated offline-data.js — refresh index.html')
